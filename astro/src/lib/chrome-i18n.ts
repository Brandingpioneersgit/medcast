const DICTS: Record<Locale, Dict> = { en, ar, ru, fr, pt, bn, tr, hi };

/**
 * Translate a chrome key for the given locale. Falls back to English when
 * a key is missing in the target locale; returns the key itself if missing
 * everywhere (so a typo surfaces visibly during dev).
 */
export function chromeT(locale: Locale, key: string): string {
  return DICTS[locale]?.[key] ?? DICTS.en[key] ?? key;
}

/**
 * Bind a translator to one locale so call sites read like `t("nav.browse")`.
 */
export function bindChromeT(locale: Locale) {
  const d = DICTS[locale] ?? DICTS.en;
  const fb = DICTS.en;
  return (key: string): string => d[key] ?? fb[key] ?? key;
}
